c5 = code_cell(
    "# Cell 5: Setup Polish Dataset & DataLoader\n"
    "import torch, torch.nn as nn\n"
    "from torch.utils.data import Dataset, DataLoader\n"
    "from PIL import Image\n"
    "import numpy as np, io, random\n"
    "\n"
    "class VQAPolishDataset(Dataset):\n"
    "    def __init__(self, samples, sz=224):\n"
    "        self.sz = sz\n"
    "        self.data = []\n"
    "        for s in samples:\n"
    "            if 'conversations' in s:\n"
    "                c = s['conversations']\n"
    "                q = c[0].get('value', 'Describe.') if c else 'Describe.'\n"
    "                a = c[-1].get('value', 'Scene.') if len(c) > 1 else 'Scene.'\n"
    "                img = s.get('image')\n"
    "            elif 'question' in s:\n"
    "                q = s['question']\n"
    "                a = s['answer']\n"
    "                img = s.get('image')\n"
    "            else:\n"
    "                continue\n"
    "            self.data.append({'img': img, 'q': str(q)[:256], 'a': str(a)[:128]})\n"
    "        print(f'Polish dataset size: {len(self.data)} samples')\n"
    "\n"
    "    def _t(self, r):\n"
    "        try:\n"
    "            if r is None:\n"
    "                return torch.rand(3, self.sz, self.sz)\n"
    "            if isinstance(r, dict) and 'bytes' in r:\n"
    "                img = Image.open(io.BytesIO(r['bytes'])).convert('RGB')\n"
    "            elif isinstance(r, Image.Image):\n"
    "                img = r.convert('RGB')\n"
    "            else:\n"
    "                return torch.rand(3, self.sz, self.sz)\n"
    "            img = img.resize((self.sz, self.sz))\n"
    "            arr = np.array(img, dtype=np.float32) / 255.0\n"
    "            return torch.from_numpy(arr).permute(2, 0, 1)\n"
    "        except Exception:\n"
    "            return torch.rand(3, self.sz, self.sz)\n"
    "\n"
    "    def __len__(self):\n"
    "        return len(self.data)\n"
    "\n"
    "    def __getitem__(self, idx):\n"
    "        d = self.data[idx]\n"
    "        return {'image': self._t(d['img']), 'question': d['q'], 'answer': d['a']}\n"
    "\n"
    "all_samples = list(adaptllm_ds)\n"
    "random.seed(42)\n"
    "random.shuffle(all_samples)\n"
    "split_idx = int(len(all_samples) * 0.9)\n"
    "train_samples = all_samples[:split_idx]\n"
    "val_samples = all_samples[split_idx:split_idx+1000]\n"
    "\n"
    "train_ds = VQAPolishDataset(train_samples)\n"
    "val_ds = VQAPolishDataset(val_samples)\n"
    "\n"
    "polish_loader = DataLoader(train_ds, batch_size=16, shuffle=True, num_workers=2, pin_memory=True, drop_last=True)\n"
    "val_loader = DataLoader(val_ds, batch_size=16, shuffle=False, num_workers=2, pin_memory=True)\n"
    "print(f'Polish Loader: {len(polish_loader)} batches | Val Loader: {len(val_loader)} batches')\n"
)

